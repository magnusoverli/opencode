/**
 * Renders the install briefing that the add-on injects into OpenCode's prompt.
 *
 * The briefing answers "what is this Home Assistant installation" once, at
 * add-on start, so conversations start oriented instead of spending their first
 * turns on discovery. It is regenerated rather than appended to, so it cannot
 * grow into a per-request tax the way a session log would.
 *
 * Pure rendering — collection lives in `home-facts.js`.
 */

import { assembleSections, byteLength, clampToBytes, fitList } from "./context-budget.js";

/**
 * Generated context lives under `/data`, not in the configuration directory.
 *
 * It is rewritten from scratch on every add-on start, so putting it where users
 * edit files would only invite edits that are silently lost — the exact trap
 * that made hand-edited `AGENTS.md` files disappear on add-on updates.
 */
export const CONTEXT_DIR = "/data/context";
export const HOME_BRIEFING_PATH = `${CONTEXT_DIR}/home-briefing.md`;

/** ~500 tokens. Small enough to stay honest on an 8k-context local model. */
export const HOME_BRIEFING_BUDGET_BYTES = 2048;

/** Per-section caps, so one large installation cannot crowd out every other section. */
const MAX_AREAS = 40;
const MAX_DOMAINS = 14;
const MAX_INTEGRATIONS = 30;
const MAX_CUSTOM_COMPONENTS = 20;
const MAX_TOP_LEVEL_KEYS = 20;
const MAX_INCLUDES = 10;

const plural = (count, singular, pluralForm = `${singular}s`) =>
  `${count} ${count === 1 ? singular : pluralForm}`;

function list(values, max) {
  const items = values.filter(Boolean);
  if (items.length <= max) return items.join(", ");
  return `${items.slice(0, max).join(", ")}, +${items.length - max} more`;
}

function renderHeader(facts) {
  const lines = [
    "# Home Assistant install briefing",
    "",
    `Generated by the OpenCode add-on at ${facts.generatedAt}. This describes how this` +
      " installation is put together so you do not have to rediscover it each session." +
      " Treat it as orientation, not as live state — check anything current with the" +
      " Home Assistant MCP tools or `hab`.",
  ];

  if (facts.degraded?.length) {
    lines.push(
      "",
      `Home Assistant Core was not reachable when this was written, so the following are missing: ${facts.degraded.join(", ")}.` +
        " Restarting the add-on regenerates the briefing.",
    );
  }

  return lines.join("\n");
}

function renderCore(core) {
  if (!core) return "";
  const parts = [];
  if (core.version) parts.push(`Home Assistant ${core.version}`);
  if (core.operatingSystem) parts.push(core.operatingSystem);
  if (core.machine) parts.push(`hardware: ${core.machine}`);
  if (core.timeZone) parts.push(`time zone: ${core.timeZone}`);
  if (core.units?.temperature) {
    const units = [core.units.temperature, core.units.length].filter(Boolean).join(", ");
    parts.push(`units: ${units}`);
  }
  if (core.language) parts.push(`language: ${core.language}`);
  if (!parts.length) return "";
  return `## Core\n${parts.join(" · ")}`;
}

/**
 * Configuration layout, most actionable bullet first.
 *
 * Ordered by what changes the model's behaviour rather than by what is
 * interesting: where new configuration should go, and which files the UI will
 * rewrite underneath an edit, matter far more than a list of top-level keys it
 * can read for itself. Under pressure the tail is what gets dropped.
 */
function renderLayout(layout, availableBytes = Infinity) {
  if (!layout) return "";

  const bullets = [];

  if (layout.packages?.configured) {
    const count =
      typeof layout.packages.fileCount === "number" ? ` (${plural(layout.packages.fileCount, "file")})` : "";
    const directory = layout.packages.directory || "packages";
    bullets.push(`- Packages are in use: \`${directory}/\`${count} — prefer adding new configuration there`);
  }

  if (layout.automations) {
    const managed = layout.automations.uiManaged
      ? " — UI-managed: the Automations editor owns this file and rewrites it on save, so hand-edits must keep every existing entry and its `id`"
      : " — hand-written (no UI `id` keys)";
    bullets.push(`- \`automations.yaml\`: ${plural(layout.automations.count, "entry", "entries")}${managed}`);
  }

  if (layout.customComponents?.length) {
    bullets.push(
      `- Custom components (${layout.customComponents.length}): ${list(layout.customComponents, MAX_CUSTOM_COMPONENTS)}` +
        " — these are not in your training data; read their source or docs before configuring them",
    );
  }

  if (layout.includes?.length) {
    const rendered = layout.includes
      .slice(0, MAX_INCLUDES)
      .map((include) => `\`${include.key}: !${include.directive} ${include.target ?? ""}\``.replace(/ \`$/, "`"));
    const extra = layout.includes.length > MAX_INCLUDES ? `, +${layout.includes.length - MAX_INCLUDES} more` : "";
    bullets.push(`- Includes: ${rendered.join(", ")}${extra}`);
  }

  const smallCounts = [];
  if (layout.scripts) smallCounts.push(`\`scripts.yaml\`: ${plural(layout.scripts.count, "script")}`);
  if (layout.scenes) smallCounts.push(`\`scenes.yaml\`: ${plural(layout.scenes.count, "scene")}`);
  if (smallCounts.length) bullets.push(`- ${smallCounts.join(" · ")}`);

  if (layout.versionControlled) {
    bullets.push("- The configuration directory is a git repository — changes are tracked, so prefer small reviewable edits");
  }

  if (layout.topLevelKeys?.length) {
    bullets.push(`- \`configuration.yaml\` top-level keys: ${list(layout.topLevelKeys, MAX_TOP_LEVEL_KEYS)}`);
  }

  const otherDirs = Object.entries(layout.directories ?? {})
    .filter(([name]) => name !== "custom_components" && name !== "packages")
    .map(([name, count]) => `${name}/ (${count})`);
  if (otherDirs.length) bullets.push(`- Also present: ${otherDirs.join(", ")}`);

  if (!bullets.length) return "";

  const heading = "## Configuration layout";
  const marker = (omitted) => `- _${omitted} further layout detail${omitted === 1 ? "" : "s"} omitted for space_`;

  const fit = (reserve) => {
    const kept = [];
    let used = byteLength(heading);
    for (const bullet of bullets) {
      const cost = byteLength(bullet) + 1;
      if (used + cost > availableBytes - reserve) break;
      kept.push(bullet);
      used += cost;
    }
    return kept;
  };

  let kept = fit(0);
  if (kept.length < bullets.length) {
    // Same rule as everywhere else: what was cut has to be visible, so the
    // marker's space is reserved before the bullets are packed.
    kept = fit(byteLength(marker(bullets.length)) + 1);
    if (!kept.length) return "";
    return [heading, ...kept, marker(bullets.length - kept.length)].join("\n");
  }

  if (!kept.length) return "";
  return [heading, ...kept].join("\n");
}

/**
 * Areas, shrunk to fit rather than dropped.
 *
 * Area names are the single most useful thing here — they are what stops the
 * model inventing "Living Room" for a home whose area is called "Stua". Listing
 * twelve of eighteen is worth far more than listing none, so this trims the list
 * to whatever room it is given.
 */
function renderAreas(areas, availableBytes = Infinity) {
  if (!areas?.length) return "";

  const heading = `## Areas (${areas.length})`;
  const trailer = "Use these exact names when targeting areas — do not invent or guess them.";
  const fixed = byteLength(`${heading}\n\n\n${trailer}`);
  const room = availableBytes === Infinity ? Infinity : availableBytes - fixed;
  if (room <= 0) return "";

  const all = areas.map((area) => (area.floor ? `${area.name} (${area.floor})` : area.name));
  const candidates = all.slice(0, MAX_AREAS);

  // The count cap and the byte budget both remove names, and the "+N more" has
  // to account for each of them or it understates what is missing.
  const renderList = (shown) => {
    const omitted = all.length - shown.length;
    return omitted ? `${shown.join(", ")}, +${omitted} more` : shown.join(", ");
  };

  const fitted = fitList(candidates, room === Infinity ? Number.MAX_SAFE_INTEGER : room);
  if (!fitted.shown) return "";

  let shown = candidates.slice(0, fitted.shown);
  let listText = renderList(shown);
  while (shown.length > 1 && room !== Infinity && byteLength(listText) > room) {
    shown = shown.slice(0, -1);
    listText = renderList(shown);
  }

  return `${heading}\n${listText}\n\n${trailer}`;
}

function renderEntities(entityCounts) {
  if (!entityCounts?.length) return "";
  const total = entityCounts.reduce((sum, entry) => sum + entry.count, 0);
  const rendered = entityCounts.slice(0, MAX_DOMAINS).map((entry) => `${entry.domain} ${entry.count}`);
  const extra =
    entityCounts.length > MAX_DOMAINS ? ` · +${entityCounts.length - MAX_DOMAINS} more domains` : "";
  return `## Entities by domain (${total} total)\n${rendered.join(" · ")}${extra}`;
}

function renderIntegrations(integrations, stacks, availableBytes = Infinity) {
  if (!integrations?.length && !stacks?.length) return "";

  const lines = [];
  let used = byteLength("## Integrations");

  // Stacks first: they shape almost every piece of advice, and they are short.
  if (stacks?.length) {
    const line = `Device stacks: ${stacks.join(", ")}`;
    if (used + byteLength(line) + 1 <= availableBytes) {
      lines.push(line);
      used += byteLength(line) + 1;
    }
  }

  if (integrations?.length) {
    const prefix = `Integrations in use (${integrations.length}): `;
    const room = availableBytes === Infinity ? Number.MAX_SAFE_INTEGER : availableBytes - used - byteLength(prefix) - 1;
    const candidates = integrations.slice(0, MAX_INTEGRATIONS);
    const fitted = room > 0 ? fitList(candidates, room) : { shown: 0, omitted: candidates.length, text: "" };

    // Both the count cap and the byte budget remove names; "+N more" has to
    // count each of them, and has to appear even when nothing at all fitted.
    const renderList = (shown) => {
      const omitted = integrations.length - shown.length;
      return omitted ? `${shown.join(", ")}${shown.length ? ", " : ""}+${omitted} more` : shown.join(", ");
    };

    let shown = candidates.slice(0, fitted.shown);
    let listText = renderList(shown);
    while (shown.length && byteLength(listText) > room) {
      shown = shown.slice(0, -1);
      listText = renderList(shown);
    }
    if (listText) lines.push(`${prefix}${listText}`);
  }

  if (!lines.length) return "";
  return `## Integrations\n${lines.join("\n")}`;
}

function renderAddon(addon) {
  if (!addon) return "";
  const on = [];
  const off = [];
  const flag = (label, enabled) => (enabled ? on : off).push(label);

  flag("Home Assistant MCP tools", addon.mcp);
  flag("YAML language server", addon.lsp);
  flag("screenshot tool (needs a model that accepts image input)", addon.screenshot);
  flag("add-on folder access (`/addons`, `/addon_configs`)", addon.addonAccess);
  flag("sensitive-file read protection", addon.restrictSensitiveFiles);

  const lines = [];
  if (on.length) lines.push(`Available: ${on.join(", ")}.`);
  if (off.length) lines.push(`Not available: ${off.join(", ")} — do not offer these.`);
  if (!lines.length) return "";
  return `## Add-on capabilities\n${lines.join(" ")}`;
}

/**
 * Render the briefing within its byte budget.
 *
 * @param {object} facts see `home-facts.js`
 * @param {{budgetBytes?: number}} [options]
 */
/** Human-readable names for the omission notice — section ids are internal. */
const SECTION_LABELS = {
  core: "Home Assistant version and settings",
  layout: "configuration layout",
  areas: "areas",
  entities: "entity counts",
  integrations: "integrations",
  addon: "add-on capabilities",
};

/**
 * Say what did not fit, so a gap is never mistaken for an absence.
 *
 * A briefing that quietly omits the area list looks exactly like a home with no
 * areas, and the model will happily invent names on that basis.
 */
function renderOmissionNotice(droppedSections) {
  const labels = droppedSections.map((id) => SECTION_LABELS[id] ?? id);
  if (!labels.length) return "";
  return (
    `_Omitted for space: ${labels.join(", ")}. Absent here does not mean absent from the installation — ` +
    "read them with the MCP tools or `hab`._"
  );
}

export function renderHomeBriefing(facts, options = {}) {
  const budgetBytes = options.budgetBytes ?? HOME_BRIEFING_BUDGET_BYTES;

  // No room at all means no briefing. Emitting a stub would spend the caller's
  // budget on something that says nothing.
  if (budgetBytes <= 0) {
    return { markdown: "", bytes: 0, includedSections: [], droppedSections: [], truncated: true };
  }

  const build = (available) => [
    { id: "header", priority: 0, required: true, text: renderHeader(facts) },
    { id: "core", priority: 1, text: renderCore(facts.core) },
    {
      id: "layout",
      priority: 2,
      min: 200,
      hasData: Boolean(facts.layout),
      render: (room) => renderLayout(facts.layout, Math.min(room, available)),
    },
    // `min` keeps room for the sections behind each shrinkable one. Areas get a
    // generous reservation on purpose: exact area names are the single thing
    // here the model cannot guess and gets wrong most visibly.
    {
      id: "areas",
      priority: 3,
      min: facts.areas?.length ? 360 : 0,
      hasData: Boolean(facts.areas?.length),
      render: (room) => renderAreas(facts.areas, Math.min(room, available)),
    },
    { id: "entities", priority: 4, text: renderEntities(facts.entityCounts) },
    {
      id: "integrations",
      priority: 5,
      min: facts.integrations?.length || facts.stacks?.length ? 120 : 0,
      hasData: Boolean(facts.integrations?.length || facts.stacks?.length),
      render: (room) => renderIntegrations(facts.integrations, facts.stacks, Math.min(room, available)),
    },
    { id: "addon", priority: 6, text: renderAddon(facts.addon) },
  ];

  // Two passes, as with the decision digest: assemble optimistically, and if
  // anything had to be left out, redo it with room set aside to say so.
  let assembled = assembleSections(build(budgetBytes), budgetBytes);
  let notice = "";

  if (assembled.droppedSections.length) {
    // Reserve against every section being named, so the notice cannot itself be
    // the thing that does not fit.
    const worstCase = renderOmissionNotice(Object.keys(SECTION_LABELS));
    const reserved = budgetBytes - byteLength(`\n\n${worstCase}`);
    if (reserved > 0) {
      assembled = assembleSections(build(reserved), reserved);
      notice = assembled.droppedSections.length ? `\n\n${renderOmissionNotice(assembled.droppedSections)}` : "";
    }
  }

  // Final backstop, applied after the notice is appended: the budget is a
  // guarantee about what reaches the prompt, not an intention.
  const markdown = `${clampToBytes(`${assembled.text}${notice}`, budgetBytes - 1).text}\n`;

  return {
    markdown,
    bytes: byteLength(markdown),
    includedSections: assembled.includedSections,
    droppedSections: assembled.droppedSections,
    truncated: assembled.truncated,
  };
}
